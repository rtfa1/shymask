#!/usr/bin/env node
/**
 * Regenerates the committed canonical face-occluder geometry in
 * `src/renderer/canonical-face.ts`.
 *
 * The depth-only face occluder must be the same face model MediaPipe fits when
 * it produces the facial transformation matrix, otherwise it would hide the
 * wrong mask fragments. The face_geometry canonical model is a stable
 * Apache-2.0 asset published by the MediaPipe project; this script pins the
 * source URL and SHA-256 so the committed table can be reproduced exactly:
 *
 *   npm run build:face-occluder
 *
 * No network access happens at app build, test or run time; only this explicit
 * regeneration fetches the source.
 */

import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceUrl =
  'https://raw.githubusercontent.com/google-ai-edge/mediapipe/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj';
const sourceSha256 = '8bac80443397e113f41a8b565ea72c59390bc031d9defab289dba7bc0c54e618';
const outputPath = path.join(root, 'src', 'renderer', 'canonical-face.ts');

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(`Could not fetch ${sourceUrl}: HTTP ${response.status}`);
}
const source = Buffer.from(await response.arrayBuffer());
const digest = createHash('sha256').update(source).digest('hex');
if (digest !== sourceSha256) {
  throw new Error(`Canonical face model checksum changed: ${digest} (expected ${sourceSha256})`);
}

const positions = [];
const indices = [];
let vertexCount = 0;
let triangleCount = 0;

for (const rawLine of source.toString('utf8').split(/\r?\n/)) {
  const line = rawLine.trim();
  if (line.startsWith('v ')) {
    const parts = line.split(/\s+/);
    const x = Number(parts[1]);
    const y = Number(parts[2]);
    const z = Number(parts[3]);
    if (![x, y, z].every(Number.isFinite)) throw new Error(`Non-finite vertex: ${line}`);
    positions.push(x, y, z);
    vertexCount += 1;
  } else if (line.startsWith('f ')) {
    const parts = line.slice(2).trim().split(/\s+/);
    if (parts.length !== 3) throw new Error(`Non-triangle face in canonical model: ${line}`);
    for (const part of parts) {
      const vertex = Number(part.split('/')[0]);
      if (!Number.isInteger(vertex) || vertex < 1 || vertex > 468) {
        throw new Error(`Face index out of range: ${line}`);
      }
      indices.push(vertex - 1);
    }
    triangleCount += 1;
  }
}

if (vertexCount !== 468) throw new Error(`Expected 468 canonical vertices, got ${vertexCount}`);
if (positions.length !== vertexCount * 3) throw new Error('Position table is not 3 values per vertex');
if (indices.length !== triangleCount * 3) throw new Error('Index table is not 3 indices per triangle');

/** Compact decimal formatting keeps the committed table readable and stable. */
function format(values, perLine) {
  const lines = [];
  for (let index = 0; index < values.length; index += perLine) {
    lines.push(`  ${values.slice(index, index + perLine).join(', ')},`);
  }
  return lines.join('\n');
}

const moduleSource = `/**
 * Canonical face surface used as a depth-only occluder in the mask scene.
 *
 * Generated by \`scripts/build-face-occluder.mjs\` from MediaPipe's
 * \`face_geometry/data/canonical_face_model.obj\` (Apache-2.0, Google LLC):
 * ${sourceUrl}
 *
 * This is the same 468-vertex canonical model that MediaPipe fits when it
 * produces the facial transformation matrix \`face_geometry\` consumes. Rendering
 * it with that matrix therefore reconstructs the tracked face surface in the
 * mask's coordinate space, so mask fragments behind the face fail the depth
 * test. It is data, not executable effect content.
 *
 * Source SHA-256: ${sourceSha256}
 */

export const CANONICAL_FACE_VERTEX_COUNT = ${vertexCount};
export const CANONICAL_FACE_TRIANGLE_COUNT = ${triangleCount};

/** Column-major xyz triplets in centimetres, canonical face space. */
export const CANONICAL_FACE_POSITIONS: readonly number[] = [
${format(positions, 6)}
];

/** Triangle indices (0-based) into the position table. */
export const CANONICAL_FACE_INDICES: readonly number[] = [
${format(indices, 12)}
];
`;

writeFileSync(outputPath, moduleSource);
console.log(
  `Wrote ${path.relative(root, outputPath)}: ${vertexCount} vertices, ${triangleCount} triangles, source sha256=${sourceSha256.slice(0, 12)}…`,
);
